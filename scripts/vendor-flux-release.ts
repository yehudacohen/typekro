/**
 * Writes `src/factories/flux/install/releases/<version>.ts` from a Flux release's
 * `install.yaml` that has already been downloaded.
 *
 * Usage: bun run scripts/vendor-flux-release.ts <version> <path/to/install.yaml>
 *
 * The file is treated as data: it is parsed with js-yaml's JSON schema (plain strings, numbers,
 * booleans, null, maps and lists) and nothing in it is evaluated. Its sha256 is recorded in the
 * generated module so a reviewer can compare it with the release asset's published digest.
 * Register the new release in `releases/index.ts` and format the output with
 * `biome format --write`.
 */
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { JSON_SCHEMA, loadAll } from 'js-yaml';

import { assertPinnedFluxVersion } from '../src/factories/flux/install/version.js';

const [version, path] = process.argv.slice(2);
if (!version || !path) {
  console.error('Usage: bun run scripts/vendor-flux-release.ts <version> <path/to/install.yaml>');
  process.exit(1);
}
assertPinnedFluxVersion(version);

const bytes = readFileSync(path);
const sha256 = createHash('sha256').update(bytes).digest('hex');
const documents = loadAll(bytes.toString('utf8'), undefined, { schema: JSON_SCHEMA }).filter(
  (document) => document !== null && document !== undefined
);

const identifier = `flux${version.replace(/^v/u, 'V').replace(/[^A-Za-z0-9]/gu, '_')}`;
const out = join(import.meta.dir, '..', 'src', 'factories', 'flux', 'install', 'releases');
const source = `/**
 * Flux ${version} install manifests, parsed from the release asset
 * https://github.com/fluxcd/flux2/releases/download/${version}/install.yaml
 * (sha256 ${sha256}).
 *
 * Generated by scripts/vendor-flux-release.ts. Do not edit by hand.
 */
// biome-ignore-all lint/suspicious/noTemplateCurlyInString: upstream CRD descriptions quote \${...} literally.
import type { FluxRelease } from '../types.js';

export const ${identifier}: FluxRelease = {
  version: ${JSON.stringify(version)},
  sourceSha256: ${JSON.stringify(sha256)},
  documents: ${JSON.stringify(documents, null, 2)},
};
`;
writeFileSync(join(out, `${version}.ts`), source);
console.log(`Wrote ${version}.ts: ${documents.length} documents, sha256 ${sha256}.`);
